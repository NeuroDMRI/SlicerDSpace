def _uniform_batch_key(images_batch):
    if not isinstance(images_batch, torch.Tensor) or images_batch.ndim != 4 or images_batch.numel() == 0:
        return None
    _, _, h, w = images_batch.shape
    first = float(images_batch[0, 0, 0, 0].item())
    if not np.isfinite(first):
        return None
    if not bool((images_batch[:, 0, h // 2, w // 2] == first).all()):
        return None
    if not bool((images_batch == first).all()):
        return None
    return (tuple(images_batch.shape), str(images_batch.dtype), first)


def _uniform_slice_key(slice_tensor):
    if not isinstance(slice_tensor, torch.Tensor) or slice_tensor.ndim != 3 or slice_tensor.numel() == 0:
        return None
    _, h, w = slice_tensor.shape
    first = float(slice_tensor[0, 0, 0].item())
    if not np.isfinite(first):
        return None
    if float(slice_tensor[0, h // 2, w // 2].item()) != first:
        return None
    if not bool((slice_tensor == first).all()):
        return None
    return (tuple(slice_tensor.shape), str(slice_tensor.dtype), first)


def _forward_fused_logits(model, sub_batch, *, use_cuda, device):
    """Run ``model`` with automatic single-slice CUDA OOM retry for low-VRAM GPUs."""
    if not use_cuda:
        _, out_list = model(sub_batch)
        return out_list[0].detach().cpu()
    try:
        _, out_list = model(sub_batch.to(device, non_blocking=True))
        return out_list[0].detach().cpu()
    except RuntimeError as exc:
        if not is_cuda_oom(exc) or sub_batch.shape[0] <= 1:
            raise
        empty_cuda_cache_safely()
        parts = []
        for idx in range(sub_batch.shape[0]):
            _, single_list = model(sub_batch[idx : idx + 1].to(device))
            parts.append(single_list[0].detach().cpu())
        return torch.cat(parts, dim=0)


def run_network(img_filename, orig_data, prediction_probability, plane, ckpts, params_model, model, logger):

    # Set up DataLoader
    test_dataset = OrigDataThickSlices_Fused_Input(img_filename, orig_data, plane=plane, transforms=transforms.Compose([ToTensorTest()]))
    test_data_loader = DataLoader(dataset=test_dataset, shuffle=False, batch_size=params_model["batch_size"])

    # Set up state dict for model
    logger.info("  -Loading {} Net from {}".format(plane, ckpts))

    backbones = copy.deepcopy(model.FastSurferCNNs) # Somthing related to parallel: may need to be "model.module.FastSurferCNNs"

    # weights_only=True restricts unpickling to a safe allow-list (tensors,
    # OrderedDict, basic scalars); only model_state["model_state_dict"] is
    # ever read below, so a full unpickle is never needed here.
    model_state = torch.load(ckpts, map_location=params_model["device"], weights_only=True)
    new_state_dict = OrderedDict()
    for k, v in model_state["model_state_dict"].items():
        if k[:7] == "module." and not params_model["model_parallel"]:
            new_state_dict[k[7:]] = v
        elif k[:7] != "module." and params_model["model_parallel"]:
            new_state_dict["module." + k] = v
        else:
            new_state_dict[k] = v
    model.load_state_dict(new_state_dict)

    print('Load backbones!')
    model.FastSurferCNNs = backbones
    model.eval()

    logger.info("  -{} model loaded.".format(plane))
    with torch.inference_mode():
        batch_count = len(test_data_loader)
        progress_interval = max(1, batch_count // 8)
        logger.info(
            "  -%s inference started: batches=%d batch_size=%d",
            plane,
            batch_count,
            params_model["batch_size"],
        )
        plane_start = time.time()

        uniform_batch_cache = {}
        uniform_slice_cache = {}
        start_index = 0
        cached_constant_temps = {}
        for batch_idx, sample_batch in enumerate(test_data_loader):
            if batch_idx == 0 or (batch_idx + 1) % progress_interval == 0 or (batch_idx + 1) == batch_count:
                logger.info(
                    "  -%s inference progress: batch %d/%d elapsed=%0.1fs",
                    plane,
                    batch_idx + 1,
                    batch_count,
                    time.time() - plane_start,
                )

            images_batch = sample_batch["image"]
            bsz = int(images_batch.shape[0])
            slice_keys = [_uniform_slice_key(images_batch[s_i]) for s_i in range(bsz)]
            if all(k is not None and k in uniform_slice_cache for k in slice_keys):
                temp_list = [torch.stack([uniform_slice_cache[k] for k in slice_keys], dim=0)]
            else:
                infer_indices = []
                pending_uniform_pos = {}
                for s_i, s_key in enumerate(slice_keys):
                    if s_key is None:
                        infer_indices.append(s_i)
                    elif s_key not in uniform_slice_cache and s_key not in pending_uniform_pos:
                        pending_uniform_pos[s_key] = len(infer_indices)
                        infer_indices.append(s_i)
                sub_batch = images_batch if len(infer_indices) == bsz else images_batch[infer_indices]
                sub_out = _forward_fused_logits(
                    model,
                    sub_batch,
                    use_cuda=params_model["use_cuda"],
                    device=params_model["device"],
                )
                batch_uniform_out = {s_key: sub_out[pos].clone() for s_key, pos in pending_uniform_pos.items()}
                for s_key, cached_val in batch_uniform_out.items():
                    if len(uniform_slice_cache) < 16:
                        uniform_slice_cache[s_key] = cached_val
                if len(infer_indices) == bsz:
                    temp_list = [sub_out]
                else:
                    infer_pos_by_slice = {orig_idx: pos for pos, orig_idx in enumerate(infer_indices)}
                    rebuilt = []
                    for s_i, s_key in enumerate(slice_keys):
                        if s_key is not None and s_key in uniform_slice_cache:
                            rebuilt.append(uniform_slice_cache[s_key])
                        elif s_key is not None and s_key in batch_uniform_out:
                            rebuilt.append(batch_uniform_out[s_key])
                        else:
                            rebuilt.append(sub_out[infer_pos_by_slice[s_i]])
                    temp_list = [torch.stack(rebuilt, dim=0)]

            # Only the fused prediction at index 0 is consumed during
            # postprocessing.  Caching every backbone prediction as a full
            # 256^3 volume wastes more than 25 GB on CPU-only Windows hosts
            # without changing the generated label map.
            for t_idx, temp in enumerate(temp_list[:1]):
                start_index_tmp = start_index
                if plane == "Axial":
                    temp = temp.permute(3, 0, 2, 1)
                    prediction_probability[t_idx, :, start_index_tmp:start_index_tmp + temp.shape[1], :, :] += torch.mul(temp.cpu(), 0.4)
                    start_index_tmp += temp.shape[1]

                elif plane == "Coronal":
                    temp = temp.permute(2, 3, 0, 1)
                    prediction_probability[t_idx, :, :, start_index_tmp:start_index_tmp + temp.shape[2], :] += torch.mul(temp.cpu(), 0.4)
                    start_index_tmp += temp.shape[2]

                else:
                    temp = map_prediction_sagittal2full(temp).permute(0, 3, 2, 1)
                    prediction_probability[t_idx, start_index_tmp:start_index_tmp + temp.shape[0], :, :, :] += torch.mul(temp.cpu(), 0.2)
                    start_index_tmp += temp.shape[0]

            start_index = start_index_tmp

        logger.info("  -%s inference finished in %0.1f seconds", plane, time.time() - plane_start)

    del test_data_loader, test_dataset, cached_constant_temps
    gc.collect()
    return prediction_probability


def fastsurfercnn(img_filename, save_as, logger, args):

    start_total = time.time()

    # Set up model for axial and coronal networks
    params_network = {'num_channels': args.num_channels, 'num_filters': args.num_filters, "num_modality": args.num_modality, "backbone_model": args.backbone_axial_path,
                      'kernel_h': args.kernel_height, 'kernel_w': args.kernel_width,
                      'stride_conv': args.stride, 'pool': args.pool,
                      'stride_pool': args.stride_pool, 'num_classes': args.num_classes_ax_cor,
                      'kernel_c': 1, 'kernel_d': 1}

    # Put it onto the GPU or CPU
    use_cuda = not args.no_cuda and torch.cuda.is_available()
    if getattr(args, "require_cuda", False) and not use_cuda:
        raise RuntimeError("DDParcel CUDA requested but no CUDA GPU is visible; fix the runtime or explicitly select CPU")
    print("On GPU!") if use_cuda else print("On CPU ...")
    if use_cuda:
        cuda_index = logical_cuda_index(args.gpu)
        if cuda_index >= torch.cuda.device_count():
            raise RuntimeError(
                f"Requested CUDA device {args.gpu}, but only {torch.cuda.device_count()} logical device(s) are visible."
            )
        device = torch.device(f"cuda:{cuda_index}")
    else:
        device = torch.device("cpu")

    if use_cuda and torch.cuda.device_count() > 1:
        model_parallel = False # TODO: Issue with using parallel with new torch verion.
    else:
        model_parallel = False

    effective_batch_size = int(args.batch_size)
    if use_cuda:
        cuda_mem = query_cuda_free_total_bytes(cuda_index)
        if cuda_mem is not None:
            free_gib = cuda_mem[0] / float(1024**3)
            if free_gib < 2.2:
                effective_batch_size = 1
            elif free_gib < 3.8:
                effective_batch_size = min(effective_batch_size, 2)

    prev_torch_threads = None
    if not use_cuda and not os.environ.get("SLICERDSPACE_STAGE_CPUS"):
        prev_torch_threads = torch.get_num_threads()
        torch.set_num_threads(optimal_cpu_torch_threads(max_conv_threads=8))

    params_model = {'device': device, "use_cuda": use_cuda, "batch_size": effective_batch_size, "model_parallel": model_parallel}
    logger.info("Cuda available: {}, # Available GPUS: {}, Cuda user disabled (--no_cuda flag): {}, --> Using device: {} (batch_size={})".format(torch.cuda.is_available(), torch.cuda.device_count(),  args.no_cuda, device, effective_batch_size))

    # Set up tensor to hold probabilities
    pred_prob = torch.zeros((1, 256, 256, 256, args.num_classes_ax_cor), dtype=torch.float)

    orig_data = []
    for idx in range(len(img_filename)):
        header_info, affine_info, orig_data_ = load_and_conform_image(img_filename[idx], interpol=1, logger=logger)
        orig_data.append(orig_data_)
        logger.info("Reading volume {}".format(img_filename[idx]))
        del orig_data_

    # Axial
    params_network["num_classes"] = args.num_classes_ax_cor
    params_network["num_channels"] = args.num_channels
    params_network["backbone_model"] = args.backbone_axial_path
    params_network["use_cuda"] = use_cuda
    model = FastSurferCNN_Fuse_Unet_v3_extended(params_network)
    if model_parallel:
        model = nn.DataParallel(model)
    model.to(device)
    start = time.time()
    pred_prob = run_network(img_filename, orig_data, pred_prob, "Axial", args.network_axial_path, params_model, model, logger)
    logger.info("Axial View Tested in {:0.4f} seconds".format(time.time() - start))
    del model
    gc.collect()

    # Coronal
    params_network["num_classes"] = args.num_classes_ax_cor
    params_network["num_channels"] = args.num_channels
    params_network["backbone_model"] = args.backbone_coronal_path
    model = FastSurferCNN_Fuse_Unet_v3_extended(params_network)
    if model_parallel:
        model = nn.DataParallel(model)
    model.to(device)
    start = time.time()
    pred_prob = run_network(img_filename,  orig_data, pred_prob, "Coronal", args.network_coronal_path, params_model, model, logger)
    logger.info("Coronal View Tested in {:0.4f} seconds".format(time.time() - start))
    del model
    gc.collect()

    # Sagittal
    params_network["num_classes"] = args.num_classes_sag
    params_network["num_channels"] = args.num_channels
    params_network["backbone_model"] = args.backbone_sagittal_path
    model = FastSurferCNN_Fuse_Unet_v3_extended(params_network)
    if model_parallel:
        model = nn.DataParallel(model)
    model.to(device)
    start = time.time()
    pred_prob = run_network(img_filename, orig_data, pred_prob, "Sagittal", args.network_sagittal_path, params_model, model, logger)
    logger.info("Sagittal View Tested in {:0.4f} seconds".format(time.time() - start))
    background_mask = orig_data[0] == -4
    del model, orig_data
    if prev_torch_threads is not None:
        torch.set_num_threads(prev_torch_threads)
    if use_cuda:
        empty_cuda_cache_safely()
    gc.collect()


    # # 保存 pred_prob 为 numpy 数组，文件名包含 subject_id
    # subject_id = args.subject_id  # 获取命令行传入的 subject_id
    # file_name = f"/data05/chengjin/DDsurfer/DDSurfer-pre-release/draft/pred_prob_{subject_id}.npy"
    # np.save(file_name, pred_prob.cpu().numpy())

    # # 修改日志信息
    # logger.info(f"Saved pred_prob to '{file_name}'")



    # Postprocessing
    # Get predictions and map to freesurfer label space
    logger.info("Starting DDSurfer postprocessing and label remapping.")
    pred_prob = pred_prob[0]
    _, pred_prob = torch.max(pred_prob, 3)
    pred_prob = pred_prob.numpy()
    pred_prob = map_label2aparc_aseg(pred_prob)

    print(f" pred_prob 1 : {pred_prob.shape}")

    # Restrict connected-component and 3D filter passes to the padded brain ROI
    # (padding=14 >= ceil(4*sigma)+2 for sigma=3 Gaussian & 3x3x3 median filters,
    # guaranteeing 100% bit-for-bit identical labels in ~1/4 the volume).
    fg_coords = np.argwhere(pred_prob != 0)
    if fg_coords.size > 0:
        pad_vox = 14
        lo = np.maximum(fg_coords.min(axis=0) - pad_vox, 0)
        hi = np.minimum(fg_coords.max(axis=0) + pad_vox + 1, np.asarray(pred_prob.shape))
        roi_slices = (slice(int(lo[0]), int(hi[0])), slice(int(lo[1]), int(hi[1])), slice(int(lo[2]), int(hi[2])))
    else:
        roi_slices = (slice(None), slice(None), slice(None))
    sub_prob = pred_prob[roi_slices]

    # Post processing - Splitting classes
    # Quick Fix for 2026 vs 1026; 2029 vs. 1029; 2025 vs. 1025
    rh_wm = get_largest_cc(sub_prob == 41)
    lh_wm = get_largest_cc(sub_prob == 2)
    rh_wm = regionprops(label(rh_wm, background=0))
    lh_wm = regionprops(label(lh_wm, background=0))
    centroid_rh = np.asarray(rh_wm[0].centroid)
    centroid_lh = np.asarray(lh_wm[0].centroid)

    # labels needs to be separated
    labels_list = np.array([1001, 1003, 1006, 1007, 1008, 1009, 1011,
                            1015, 1018, 1019, 1020, 1025, 1026, 1027, 1028, 1029, 1030, 1031, 1032, 1033, 1034, 1035])

    label_img = sub_prob
    for label_current in labels_list:
        mask_cur = sub_prob == label_current
        if not np.any(mask_cur):
            continue
        label_img = label(mask_cur, connectivity=3, background=0)
        for region in regionprops(label_img):
            if region.label != 0:  # To avoid background
                if np.linalg.norm(np.asarray(region.centroid) - centroid_rh) < np.linalg.norm(np.asarray(region.centroid) - centroid_lh):
                    sub_prob[region.slice][region.image] = label_current + 1000

    print(f" label_img 1 : {pred_prob.shape}")

    # Quick Fixes for overlapping classes
    aseg_lh = gaussian_filter(1000 * np.asarray(sub_prob == 2, dtype=np.float32), sigma=3)
    aseg_rh = gaussian_filter(1000 * np.asarray(sub_prob == 41, dtype=np.float32), sigma=3)
    lh_rh_right = aseg_rh > aseg_lh

    # Problematic classes: 1026, 1011, 1029, 1019
    for prob_class_lh in [1011, 1019, 1026, 1029, 1032]:
        prob_class_rh = prob_class_lh + 1000
        both = (sub_prob == prob_class_lh) | (sub_prob == prob_class_rh)
        if not np.any(both):
            continue
        sub_prob[both & (~lh_rh_right)] = prob_class_lh
        sub_prob[both & lh_rh_right] = prob_class_rh

    print(f" pred_prob 2 : {pred_prob.shape}")

    # Clean-Up
    if args.cleanup is True:

        labels = [2, 4, 5, 7, 8, 10, 11, 12, 13, 14,
                  15, 16, 17, 18, 24, 26, 28, 31, 41, 43, 44,
                  46, 47, 49, 50, 51, 52, 53, 54, 58, 60, 63,
                  77, 1026, 2026]

        start = time.time()
        sub_prob_medfilt = median_filter(sub_prob, size=(3, 3, 3))
        mask = np.zeros_like(sub_prob)
        tolerance = 25

        for current_label in labels:
            current_class = (sub_prob == current_label)
            if not np.any(current_class):
                continue
            label_image = label(current_class, connectivity=3)

            for region in regionprops(label_image):
                if region.area <= tolerance:
                    mask[region.slice][region.image] = 1

        sub_prob[mask == 1] = sub_prob_medfilt[mask == 1]
        logger.info("Segmentation Cleaned up in {:0.4f} seconds.".format(time.time() - start))

    pred_prob[background_mask] = 0

    print(f" pred_prob 3 : {pred_prob.shape}")

    # Saving image
    logger.info("DDSurfer postprocessing complete; writing final segmentation.")
    header_info.set_data_dtype(np.int16)
    mapped_aseg_img = nib.MGHImage(pred_prob, affine_info, header_info)
    mapped_aseg_img.to_filename(save_as)

    logger.info("Saving Segmentation to {}".format(save_as))
    logger.info("Total processing time: {:0.4f} seconds.".format(time.time() - start_total))


if __name__ == "__main__":

    # Command Line options and error checking done here
    options = options_parse()

    # Set up the logger
    logger = logging.getLogger("eval")
    logger.setLevel(logging.DEBUG)
    logger.addHandler(logging.StreamHandler(stream=sys.stdout))

    fastsurfercnn(options.iname, options.oname, logger, options)
